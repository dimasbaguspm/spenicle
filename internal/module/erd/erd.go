package erd

import (
	"context"
	"fmt"
	"strings"

	telemetry "github.com/dimasbaguspm/spenicle/internal/common/otel"
	"github.com/dimasbaguspm/spenicle/internal/repository/schema"
)

const internalTable = "schema_migrations"

type Service struct {
	introspector schema.Introspector
}

func New(introspector schema.Introspector) *Service {
	return &Service{introspector: introspector}
}

func (s *Service) Document(ctx context.Context) (string, error) {
	ctx, endSpan := telemetry.StartSpan(ctx, "Module.Erd.Document")
	defer endSpan()

	tables, err := s.introspector.Tables(ctx)
	if err != nil {
		return "", fmt.Errorf("read schema: %w", err)
	}

	return render(tables), nil
}

func render(tables []schema.Table) string {
	var document strings.Builder

	document.WriteString("<!-- generated by `make erd` from the embedded migrations; do not edit -->\n")
	document.WriteString("# Entity relationships\n\n")
	document.WriteString("The schema as the database reports it. " +
		"Regenerate with `make erd` after a migration.\n\n")
	document.WriteString("```mermaid\nerDiagram\n")

	entities := make([]schema.Table, 0, len(tables))

	for _, table := range tables {
		if table.Name == internalTable {
			continue
		}

		entities = append(entities, table)
	}

	for _, table := range entities {
		document.WriteString("\n    " + identifier(table.Name) + " {\n")

		references := referenceColumns(table)

		for _, column := range table.Columns {
			document.WriteString("        " + attribute(column, references[column.Name]) + "\n")
		}

		document.WriteString("    }\n")
	}

	for _, table := range entities {
		for _, reference := range table.References {
			fmt.Fprintf(&document, "    %s ||--o{ %s : \"%s\"\n",
				identifier(reference.Table), identifier(table.Name), reference.Column)
		}
	}

	document.WriteString("```\n")

	return document.String()
}

func attribute(column schema.Column, foreign bool) string {
	keys := make([]string, 0, 2)

	if column.PrimaryKey {
		keys = append(keys, "PK")
	}

	if foreign {
		keys = append(keys, "FK")
	}

	line := typeName(column.Type) + " " + identifier(column.Name)
	if len(keys) > 0 {
		line += " " + strings.Join(keys, ",")
	}

	return line
}

func referenceColumns(table schema.Table) map[string]bool {
	out := make(map[string]bool, len(table.References))

	for _, reference := range table.References {
		out[reference.Column] = true
	}

	return out
}

func identifier(name string) string {
	cleaned := strings.Map(func(char rune) rune {
		switch {
		case char >= 'a' && char <= 'z', char >= 'A' && char <= 'Z',
			char >= '0' && char <= '9', char == '_':
			return char
		default:
			return '_'
		}
	}, name)

	if cleaned == "" {
		return "unnamed"
	}

	return cleaned
}

func typeName(raw string) string {
	cleaned := strings.Map(func(char rune) rune {
		switch {
		case char >= 'A' && char <= 'Z', char >= '0' && char <= '9', char == '_':
			return char
		case char >= 'a' && char <= 'z':
			return char - ('a' - 'A')
		default:
			return '_'
		}
	}, raw)

	if cleaned == "" {
		return "TEXT"
	}

	return cleaned
}
